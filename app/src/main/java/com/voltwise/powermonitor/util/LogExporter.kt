package com.voltwise.powermonitor.util

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import com.voltwise.powermonitor.data.repository.PowerRepository
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileWriter

object LogExporter {

    suspend fun exportHistoryToCsv(context: Context, repository: PowerRepository): Intent? = withContext(Dispatchers.IO) {
        val batteryLogs = repository.getAllBatteryLogsForExport()
        val appLogs = repository.getAllAppLogsForExport()

        if (batteryLogs.isEmpty() && appLogs.isEmpty()) {
            return@withContext null
        }

        val exportDir = File(context.cacheDir, "exports")
        if (!exportDir.exists()) {
            exportDir.mkdirs()
        }

        val filename = "voltwise_telemetry_report_${FormatUtils.formatFileTimestamp(System.currentTimeMillis())}.csv"
        val csvFile = File(exportDir, filename)

        FileWriter(csvFile).use { writer ->
            // Section 1: Hardware Battery Telemetry
            writer.append("=== VOLTWISE BATTERY TELEMETRY LOGS ===\n")
            writer.append("Timestamp,DateTime,BatteryLevel(%),Voltage(mV),Temperature(C),Current(mA),Power(mW),Status,PlugType,ScreenActive\n")

            for (log in batteryLogs) {
                writer.append("${log.timestamp},")
                writer.append("\"${FormatUtils.formatDateTime(log.timestamp)}\",")
                writer.append("${log.level},")
                writer.append("${log.voltageMv},")
                writer.append("${String.format("%.1f", log.temperatureCelsius)},")
                writer.append("${String.format("%.1f", log.currentMa)},")
                writer.append("${String.format("%.1f", log.powerMw)},")
                writer.append("${log.status},")
                writer.append("${log.plugType},")
                writer.append("${log.screenOn}\n")
            }

            writer.append("\n\n")

            // Section 2: App Activity and Energy Attribution
            writer.append("=== APPLICATION POWER & ACTIVITY ATTRIBUTION ===\n")
            writer.append("Timestamp,DateTime,AppName,PackageName,ForegroundDuration(ms),ForegroundFormatted,EstPower(mAh),PercentOfTotal(%),StandbyBucket,IsSystemApp\n")

            for (app in appLogs) {
                writer.append("${app.timestamp},")
                writer.append("\"${FormatUtils.formatDateTime(app.timestamp)}\",")
                writer.append("\"${app.appName.replace("\"", "\"\"")}\",")
                writer.append("\"${app.packageName}\",")
                writer.append("${app.foregroundDurationMs},")
                writer.append("\"${FormatUtils.formatDuration(app.foregroundDurationMs)}\",")
                writer.append("${app.estimatedPowerMah},")
                writer.append("${app.percentageOfTotal},")
                writer.append("${app.standbyBucket},")
                writer.append("${app.isSystemApp}\n")
            }

            writer.flush()
        }

        val authority = "${context.packageName}.fileprovider"
        val contentUri = FileProvider.getUriForFile(context, authority, csvFile)

        Intent(Intent.ACTION_SEND).apply {
            type = "text/csv"
            putExtra(Intent.EXTRA_STREAM, contentUri)
            putExtra(Intent.EXTRA_SUBJECT, "VoltWise Battery & Power Monitoring Report")
            putExtra(Intent.EXTRA_TEXT, "Exported battery power and application activity telemetry data generated by VoltWise.")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
    }
}
